"""Generate a versioned browser dataset from approved claims only."""
from __future__ import annotations

from collections import Counter
from pathlib import Path
from typing import Any

from .common import dump_json, utc_now


def generate_dataset(approved: list[dict[str, Any]], scenario: dict[str, Any], output_path: str | Path) -> dict[str, Any]:
    for record in approved:
        review = record.get("review")
        if not isinstance(review, dict) or review.get("reviewed") is not True or review.get("status") != "approved":
            raise ValueError(f"refusing to export unreviewed or unapproved claim: {record.get('claim_id')}")
    groups: dict[str, list[dict[str, Any]]] = {}
    for record in approved:
        groups.setdefault(record["candidate_id"], []).append(record)
    sources = []
    claims = []
    for index, (candidate_id, records) in enumerate(sorted(groups.items()), 1):
        representative = max(records, key=lambda x: (x["confidence"], len(x["evidence_quote"]), x["source"]["votes"]))
        known: dict[str, Any] = {}
        for key in scenario["conditions"]:
            stated = {x["conditions"][key] for x in records if x["conditions"][key] is not None}
            known[key] = next(iter(stated)) if len(stated) == 1 else None
        lean_scores = {"capsule": 0, "semi": 0}
        for record in records:
            if record["polarity"] == "pro":
                lean_scores[record["option"]] += 1
            else:
                other = next(x["id"] for x in scenario["options"] if x["id"] != record["option"])
                lean_scores[other] += 1
        leans = max(lean_scores, key=lean_scores.get) if lean_scores["capsule"] != lean_scores["semi"] else None
        source_id = f"{scenario['id']}-s{index}"
        source = {
            "id": source_id,
            "kind": Counter(x["source_type"] for x in records).most_common(1)[0][0],
            "leans": leans,
            "author": representative["source"]["author"],
            "badge": representative["source"]["badge"],
            "votes": representative["source"]["votes"],
            "title": representative["source"]["title"],
            "url": representative["source"]["url"],
            "quote": representative["evidence_quote"],
            "known": known,
        }
        sources.append(source)
        for record in records:
            claims.append({
                "claim_id": record["claim_id"],
                "candidate_id": record["candidate_id"],
                "source_id": source_id,
                "source": record["source"],
                **{key: record[key] for key in ["claim", "option", "polarity", "evidence_quote", "conditions", "cost", "source_type", "confidence"]},
                "evidence_start": record["evidence_start"],
                "evidence_end": record["evidence_end"],
                "reviewed": record["review"]["reviewed"],
            })
    stats = {
        "source_count": len(sources),
        "claim_count": len(claims),
        "source_type_counts": dict(Counter(x["source_type"] for x in claims)),
        "option_counts": dict(Counter(x["option"] for x in claims)),
        "polarity_counts": dict(Counter(x["polarity"] for x in claims)),
        "condition_coverage": {key: sum(x["conditions"][key] is not None for x in claims) for key in scenario["conditions"]},
    }
    js = "/* Generated by aiworks extraction pipeline. Approved records only. */\n"
    js += "window.PIPELINE_META = " + _json({"scenario": scenario["id"], "generated_at": utc_now(), "prompt_version": "see approved-extractions.json", "reviewed_only": True}) + ";\n"
    js += "window.PIPELINE_SOURCES = " + _json(sources) + ";\n"
    js += "window.PIPELINE_CLAIMS = " + _json(claims) + ";\n"
    js += "window.PIPELINE_STATS = " + _json(stats) + ";\n"
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(js, encoding="utf-8")
    dump_json(output_path.with_suffix(".stats.json"), stats)
    return stats


def _json(value: Any) -> str:
    import json
    return json.dumps(value, ensure_ascii=False, separators=(",", ":")).replace("<", "\\u003c")
